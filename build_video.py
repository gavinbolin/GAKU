"""build_video.py — Build a YouTube-ready MP4 from an existing podcast episode.

Reads an episode.json + pre-rendered audio (clip_durations.json, episode.wav),
generates a full visual manifest via visual_queue, renders each visual clip
through Remotion, then composes the final MP4 with ffmpeg.

Usage:
    python podcast-pipeline/build_video.py \
        --episode output/episode_quickbooks.json \
        --build-dir output/build_quickbooks \
        --out output/quickbooks-pain-points-001.mp4

Short preview slices (no upload), e.g. two windows in global seconds:
    python build_video.py --episode run/episode.json --build-dir run \
        --out run/preview.mp4 --preview 225-270 --preview 508-560
Plan only (writes visual_manifest.json + visual_plan_report.json):
    python build_video.py --episode ... --build-dir ... --out x.mp4 --manifest-only
"""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent

try:
    from dotenv import load_dotenv
    load_dotenv(HERE.parent / ".env", override=False)
except ImportError:
    pass

# visual_queue is imported lazily in main() so compose-only remux works
# without loading Remotion/Pexels helpers.
sys.path.insert(0, str(HERE))

REMOTION_PKG_DIR = HERE / "packages" / "remotion"
REMOTION_ENTRY = REMOTION_PKG_DIR / "src" / "Root.tsx"
FPS = 30


def _try_youtube_upload(
    mp4_path: Path,
    episode: dict | None = None,
    run_dir: Path | None = None,
) -> None:
    """Private YouTube upload after compose. Only raises MissingSourcesError (no sources)."""
    repo_root = HERE.parent
    if not (repo_root / "youtube_client_secrets.json").exists():
        print("[youtube] skipping — youtube_client_secrets.json not found", file=sys.stderr)
        return
    prev = os.getcwd()
    try:
        os.chdir(repo_root)
        if str(repo_root) not in sys.path:
            sys.path.insert(0, str(repo_root))
        import datetime
        import youtube_upload as yt

        topic = (episode or {}).get("topic") or mp4_path.stem
        segs = len((episode or {}).get("segments") or [])
        extra = f" — {segs} segments" if segs else ""
        description = (
            f"{topic}\n\n"
            f"Generated by PROJECT GAKU{extra} — "
            f"{datetime.date.today().strftime('%B %d, %Y')}\n\n"
            "This video was auto-generated using AI research, scripting, and text-to-speech synthesis.\n\n"
            "This episode uses AI-generated voices and visuals (PROJECT GAKU)."
        )
        import episode_sources as es
        src_dir = run_dir if run_dir is not None and (Path(run_dir) / "episode.json").exists() else mp4_path.parent
        description, _ = es.build_description(description, src_dir, episode)  # GAKU_ALLOW_NO_SOURCES=1 overrides
        tags = (episode or {}).get("keywords") or ["podcast", "education", "gaku"]
        privacy = os.environ.get("GAKU_YT_PRIVACY", "private")
        # Prefer episode folder for thumbnail.png override / hybrid gen.
        episode_dir = None
        if run_dir is not None:
            episode_dir = Path(run_dir)
        elif mp4_path.parent.name and (mp4_path.parent / "episode.json").exists():
            episode_dir = mp4_path.parent

        result = yt.upload_video(
            str(mp4_path),
            title=str(topic)[:100],
            description=description,
            tags=tags,
            privacy_status=privacy,
            episode_dir=str(episode_dir) if episode_dir else None,
            episode=episode,
        )
        out = {**result, "uploaded_at": datetime.datetime.utcnow().isoformat() + "Z"}
        dest = run_dir or mp4_path.parent
        (dest / "youtube.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
        print(f"[youtube] {result.get('url')} ({privacy})", file=sys.stderr)
    except Exception as exc:
        if type(exc).__name__ == "MissingSourcesError":
            print(f"[youtube] REFUSED: {exc}", file=sys.stderr)
            print(f"[youtube] video is still saved locally at: {mp4_path}", file=sys.stderr)
            raise
        print(f"[youtube] upload failed: {exc}", file=sys.stderr)
        print(f"[youtube] video is still saved locally at: {mp4_path}", file=sys.stderr)
    finally:
        os.chdir(prev)




def _quote_win(arg: str) -> str:
    """Quote an argument for cmd.exe if it contains spaces or special chars."""
    if sys.platform != "win32":
        return arg
    if all(c.isalnum() or c in "_=-:./\\" for c in arg):
        return arg
    return f'"{arg}"'


def render_one_clip(
    template: str,
    data: dict,
    duration_ms: int,
    out_path: Path,
    frame_range: tuple[int, int] | None = None,
) -> None:
    """Render a single Remotion composition to MP4.

    frame_range=(a, b) renders only frames a..b (inclusive) of the clip; used
    by --preview so a test slice doesn't render whole 5-minute segments."""
    frames = max(1, round(duration_ms / 1000 * FPS))
    props = {**data, "durationInFrames": frames}

    with tempfile.TemporaryDirectory(prefix="gaku-props-") as tmp:
        props_path = Path(tmp) / "props.json"
        props_path.write_text(json.dumps(props), encoding="utf-8")

        raw_args = [
            "remotion", "render",
            "src/Root.tsx",
            template,
            str(out_path),
            f"--props={props_path}",
            f"--duration-in-frames={frames}",
            f"--fps={FPS}",
        ]
        if frame_range is not None:
            a, b = frame_range
            a = max(0, min(frames - 1, int(a)))
            b = max(a, min(frames - 1, int(b)))
            raw_args.append(f"--frames={a}-{b}")
        # On Windows with shell=True, subprocess concatenates the list into a
        # single string for cmd.exe. Paths containing spaces (e.g. "PROJECT
        # GAKU") must be quoted so cmd.exe treats them as single tokens.
        npx = shutil.which("npx.cmd") or r"C:\Program Files\nodejs\npx.cmd"
        cmd = [npx, "--yes"] + raw_args

        print(f"  [render] {template} -> {out_path.name} ({duration_ms}ms, {frames}f)", file=sys.stderr)
        result = subprocess.run(
            cmd,
            cwd=str(REMOTION_PKG_DIR),
            capture_output=True,
            text=True,
            timeout=1800,
        )
        if result.returncode != 0:
            print(f"  [render] STDERR:\n{result.stderr}", file=sys.stderr)
            raise RuntimeError(f"Remotion render failed for {template} (exit {result.returncode})")


def _wav_duration_s(path: Path) -> float | None:
    """Return WAV duration in seconds, or None if the file is not a WAV."""
    try:
        import wave
        with wave.open(str(path), "rb") as wf:
            rate = wf.getframerate()
            if rate:
                return wf.getnframes() / float(rate)
    except Exception:
        return None
    return None


def compose_with_ffmpeg(
    audio_path: Path,
    visuals: list[dict],
    out_path: Path,
    total_duration_ms: int,
    width: int = 1920,
    height: int = 1080,
) -> None:
    """Compose visuals into a single MP4 using ffmpeg xfade concat + audio mux.

    Visuals must be sorted by start_ms and contiguous (each clip covers its
    full duration so back-to-back xfade is correct).

    Non-last clips are tpad-extended by TRANSITION_S so the xfade overlap
    consumes cloned pad frames, not content. Offset is the unpadded cumulative
    duration (NOT cumulative - i*TRANSITION_S). Resulting video duration equals
    sum(clip durations). Falls back to concat hard-cuts if xfade fails.
    """
    if not visuals:
        raise RuntimeError("No visuals to compose")

    TRANSITION_S = 0.5

    # Build inputs: each visual file + audio last.
    input_args = ["-y", "-hide_banner", "-loglevel", "warning"]
    clip_durations_s = []
    for v in visuals:
        input_args.extend(["-i", str(v["path"])])
        dur_ms = v.get("duration_ms") or (v.get("end_ms", 0) - v.get("start_ms", 0))
        clip_durations_s.append(max(0.1, dur_ms / 1000))
    input_args.extend(["-i", str(audio_path)])
    audio_idx = len(visuals)
    n = len(visuals)
    last_i = n - 1

    audio_s = _wav_duration_s(audio_path)
    dur_s = audio_s if audio_s else (total_duration_ms / 1000)

    def _prep(i: int, clip_s: float, *, pad: bool) -> str:
        chain = (
            f"[{i}:v]scale={width}:{height}:force_original_aspect_ratio=decrease,"
            f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2,setsar=1,fps={FPS},"
            f"trim=duration={clip_s:.3f},setpts=PTS-STARTPTS"
        )
        if pad:
            chain += f",tpad=stop_mode=clone:stop_duration={TRANSITION_S:.3f}"
        chain += f"[v{i}]"
        return chain

    def _ffmpeg(filter_parts: list[str], vmap: str, method: str) -> subprocess.CompletedProcess:
        args = [
            "ffmpeg",
            *input_args,
            "-filter_complex", ";".join(filter_parts),
            "-map", vmap,
            "-map", f"{audio_idx}:a",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "veryfast", "-crf", "23",
            "-c:a", "aac", "-b:a", "128k",
            "-movflags", "+faststart",
            "-stats",
            "-t", f"{dur_s:.3f}",
            str(out_path),
        ]
        print(f"  [compose] Running ffmpeg ({method}) with {n} visual inputs...", file=sys.stderr)
        return subprocess.run(args, capture_output=True, text=True, timeout=1800)

    # Padded xfade: clone last frame on every clip except the last so the 0.5s
    # overlap eats PAD, not content. Offset = unpadded cumulative duration.
    filter_parts = [
        _prep(i, clip_s, pad=(i != last_i))
        for i, clip_s in enumerate(clip_durations_s)
    ]
    if n == 1:
        last_label = "v0"
    else:
        cumulative_s = 0.0
        prev_label = "v0"
        for i in range(1, n):
            cumulative_s += clip_durations_s[i - 1]
            offset_s = cumulative_s  # unpadded; pad is what xfade consumes
            out_label = "vout" if i == last_i else f"vx{i}"
            filter_parts.append(
                f"[{prev_label}][v{i}]xfade=transition=fade:"
                f"duration={TRANSITION_S:.3f}:offset={offset_s:.3f}[{out_label}]"
            )
            prev_label = out_label
        last_label = prev_label

    result = _ffmpeg(filter_parts, f"[{last_label}]", "padded xfade")
    if result.returncode == 0:
        print(f"  [compose] Done (padded xfade) -> {out_path}", file=sys.stderr)
        return

    print("  [compose] padded xfade failed; falling back to concat hard cuts", file=sys.stderr)
    print(f"  [compose] STDERR:\n{result.stderr}", file=sys.stderr)

    concat_parts = [_prep(i, clip_s, pad=False) for i, clip_s in enumerate(clip_durations_s)]
    concat_inputs = "".join(f"[v{i}]" for i in range(n))
    concat_parts.append(f"{concat_inputs}concat=n={n}:v=1:a=0[vout]")
    result = _ffmpeg(concat_parts, "[vout]", "concat")
    if result.returncode != 0:
        print(f"  [compose] STDERR:\n{result.stderr}", file=sys.stderr)
        raise RuntimeError(f"ffmpeg compose failed (exit {result.returncode})")
    print(f"  [compose] Done (concat) -> {out_path}", file=sys.stderr)


def _parse_window(spec: str) -> tuple[float, float]:
    a, _, b = spec.partition("-")
    start, end = float(a), float(b)
    if end <= start:
        raise ValueError(f"bad --preview window {spec!r} (want START-END seconds)")
    return start, end


def render_preview(
    visuals: list[dict],
    audio_path: Path,
    windows: list[tuple[float, float]],
    visuals_dir: Path,
    out_path: Path,
) -> list[Path]:
    """Render only the parts of the manifest that overlap each window (global
    seconds) via Remotion --frames, hard-cut them together, mux the matching
    audio slice, and concatenate windows into out_path. Returns window files."""
    prev_dir = visuals_dir / "preview"
    prev_dir.mkdir(parents=True, exist_ok=True)
    window_files: list[Path] = []
    for wi, (ws, we) in enumerate(windows, 1):
        w0, w1 = int(ws * 1000), int(we * 1000)
        pieces: list[Path] = []
        for v in sorted(visuals, key=lambda x: x.get("start_ms", 0)):
            vs, ve = int(v.get("start_ms", 0)), int(v.get("end_ms", 0))
            lo, hi = max(vs, w0), min(ve, w1)
            if hi - lo < 100:
                continue
            fa = int(round((lo - vs) / 1000 * FPS))
            fb = int(round((hi - vs) / 1000 * FPS)) - 1
            piece = prev_dir / f"w{wi:02d}_{v['visual_id']}_{fa}-{fb}.mp4"
            render_one_clip(v["template"], v.get("data", {}), ve - vs, piece, frame_range=(fa, fb))
            pieces.append(piece)
        if not pieces:
            print(f"  [preview] window {ws}-{we}s overlaps no visuals; skipped", file=sys.stderr)
            continue
        wfile = prev_dir / f"window_{wi:02d}_{int(ws)}-{int(we)}s.mp4"
        inputs: list[str] = []
        chains: list[str] = []
        for i, pth in enumerate(pieces):
            inputs += ["-i", str(pth)]
            chains.append(f"[{i}:v]scale=1920:1080,setsar=1,fps={FPS},setpts=PTS-STARTPTS[v{i}]")
        concat = "".join(f"[v{i}]" for i in range(len(pieces))) + f"concat=n={len(pieces)}:v=1:a=0[vout]"
        args = [
            "ffmpeg", "-y", "-hide_banner", "-loglevel", "warning",
            *inputs,
            "-ss", f"{ws:.3f}", "-t", f"{we - ws:.3f}", "-i", str(audio_path),
            "-filter_complex", ";".join(chains + [concat]),
            "-map", "[vout]", "-map", f"{len(pieces)}:a",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "veryfast", "-crf", "20",
            "-c:a", "aac", "-b:a", "128k", "-shortest", str(wfile),
        ]
        r = subprocess.run(args, capture_output=True, text=True, timeout=900)
        if r.returncode != 0:
            raise RuntimeError(f"preview window ffmpeg failed: {r.stderr[-1500:]}")
        window_files.append(wfile)
        print(f"  [preview] window {ws:.1f}-{we:.1f}s -> {wfile.name} ({len(pieces)} pieces)", file=sys.stderr)
    if window_files:
        lst = prev_dir / "concat.txt"
        lst.write_text("".join(f"file '{w.as_posix()}'\n" for w in window_files), encoding="utf-8")
        r = subprocess.run(
            ["ffmpeg", "-y", "-hide_banner", "-loglevel", "warning", "-f", "concat", "-safe", "0",
             "-i", str(lst), "-c", "copy", str(out_path)],
            capture_output=True, text=True, timeout=600,
        )
        if r.returncode != 0:
            raise RuntimeError(f"preview concat failed: {r.stderr[-1500:]}")
    return window_files


def main() -> int:
    parser = argparse.ArgumentParser(description="Build YouTube-ready MP4 from podcast episode.")
    parser.add_argument("--episode", help="Path to episode.json")
    parser.add_argument("--build-dir", required=True, help="Build directory (must contain clips/, clip_durations.json, episode.wav)")
    parser.add_argument("--out", required=True, help="Output MP4 path")
    parser.add_argument("--skip-render", action="store_true", help="Skip Remotion rendering (reuse existing clips)")
    parser.add_argument(
        "--compose-only",
        action="store_true",
        help="Remux existing visuals from summary.json; skip manifest + Remotion",
    )
    parser.add_argument(
        "--no-upload",
        action="store_true",
        help="Skip YouTube upload even if OAuth credentials are present (school listens, tests).",
    )
    parser.add_argument(
        "--reuse-manifest",
        action="store_true",
        help="Reuse <build-dir>/visual_manifest.json instead of re-planning (keeps Pexels picks).",
    )
    parser.add_argument(
        "--manifest-only",
        action="store_true",
        help="Build visual_manifest.json + visual_plan_report.json and stop (no render, no upload).",
    )
    parser.add_argument(
        "--preview",
        action="append",
        default=[],
        metavar="START-END",
        help="Render only this global-seconds window (repeatable) into --out. Implies --no-upload.",
    )
    args = parser.parse_args()
    if args.preview or args.manifest_only:
        args.no_upload = True

    build_dir = Path(args.build_dir).resolve()
    out_path = Path(args.out).resolve()
    visuals_dir = build_dir / "visuals"
    visuals_dir.mkdir(parents=True, exist_ok=True)

    if args.compose_only:
        summary_path = build_dir / "summary.json"
        if not summary_path.exists():
            print(f"ERROR: summary.json not found at {summary_path}", file=sys.stderr)
            return 1
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        audio_path = build_dir / "episode.wav"
        if not audio_path.exists():
            audio_path = build_dir / "podcast.wav"
        if not audio_path.exists():
            candidate = Path(summary.get("audio_path") or "")
            if candidate.exists():
                audio_path = candidate
        if not audio_path.exists():
            print(f"ERROR: episode.wav not found under {build_dir}", file=sys.stderr)
            return 1
        compose_visuals = []
        for v in summary.get("visuals", []):
            clip = Path(v.get("path") or "")
            if not clip.exists():
                clip = visuals_dir / f"{v['visual_id']}.mp4"
            if not clip.exists():
                print(f"ERROR: missing clip {v.get('visual_id')} ({clip})", file=sys.stderr)
                return 1
            item = dict(v)
            item["path"] = str(clip)
            compose_visuals.append(item)
        compose_visuals.sort(key=lambda x: x.get("start_ms", 0))
        if not compose_visuals:
            print("ERROR: summary.json has no visuals to compose", file=sys.stderr)
            return 1
        audio_s = _wav_duration_s(audio_path)
        total_ms = int(round(audio_s * 1000)) if audio_s else int(summary.get("final_duration_ms") or 0)
        print("[compose-only] Remuxing existing clips (no Remotion, no manifest)...", file=sys.stderr)
        print(f"  {len(compose_visuals)} clips, audio {audio_path}", file=sys.stderr)
        compose_with_ffmpeg(audio_path, compose_visuals, out_path, total_ms)
        print(f"\nDone! Output: {out_path}", file=sys.stderr)
        if not args.no_upload:
            _try_youtube_upload(out_path, run_dir=build_dir)
        return 0

    if not args.episode:
        parser.error("--episode is required unless --compose-only")

    episode_path = Path(args.episode).resolve()

    # Load episode + clip durations.
    episode = json.loads(episode_path.read_text(encoding="utf-8"))
    clip_dur_path = build_dir / "clip_durations.json"
    if not clip_dur_path.exists():
        print(f"ERROR: clip_durations.json not found at {clip_dur_path}", file=sys.stderr)
        return 1
    clip_durations = json.loads(clip_dur_path.read_text(encoding="utf-8"))

    audio_path = build_dir / "episode.wav"
    if not audio_path.exists():
        audio_path = build_dir / "podcast.wav"  # research_podcast run dirs
    if not audio_path.exists():
        print(f"ERROR: episode.wav / podcast.wav not found under {build_dir}", file=sys.stderr)
        return 1

    # Step 1: Build full visual manifest via visual_queue.
    manifest_path = build_dir / "visual_manifest.json"
    if args.reuse_manifest and manifest_path.exists():
        print(f"[1/3] Reusing {manifest_path}", file=sys.stderr)
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    else:
        from visual_queue import build_visual_manifest
        print("[1/3] Building visual manifest...", file=sys.stderr)
        manifest = build_visual_manifest(
            episode=episode,
            clip_durations=clip_durations,
            run_dir=build_dir,
            pexels_key=os.environ.get("PEXELS_API_KEY"),
            audio_path=audio_path,
        )
    total_ms = manifest["total_duration_ms"]
    visuals = manifest["visuals"]
    print(f"  Manifest: {len(visuals)} visuals, total {total_ms}ms ({total_ms/1000:.1f}s)", file=sys.stderr)

    if not visuals:
        print("ERROR: manifest produced no visuals", file=sys.stderr)
        return 1
    if args.manifest_only:
        print(f"  --manifest-only: wrote {manifest_path}", file=sys.stderr)
        return 0
    if args.preview:
        windows = [_parse_window(w) for w in args.preview]
        print(f"[preview] rendering {len(windows)} window(s) -> {out_path}", file=sys.stderr)
        render_preview(visuals, audio_path, windows, visuals_dir, out_path)
        print(f"\nDone! Preview: {out_path} (no upload)", file=sys.stderr)
        return 0

    # Step 2: Render each visual clip via Remotion.
    print(f"[2/3] Rendering {len(visuals)} visual clips...", file=sys.stderr)
    for v in visuals:
        vid = v["visual_id"]
        template = v["template"]
        data = v.get("data", {})
        dur_ms = v.get("end_ms", 0) - v.get("start_ms", 0)
        if dur_ms <= 0:
            dur_ms = v.get("duration_ms", 5000)

        clip_path = visuals_dir / f"{vid}.mp4"
        v["path"] = str(clip_path)
        v["duration_ms"] = dur_ms

        if args.skip_render and clip_path.exists():
            print(f"  [render] Skipping {vid} (exists)", file=sys.stderr)
            continue

        render_one_clip(template, data, dur_ms, clip_path)

    # Step 3: Compose final video.
    print("[3/3] Composing final MP4...", file=sys.stderr)

    # Build compose payload — sorted by start_ms.
    compose_visuals = sorted(
        [v for v in visuals if v.get("path") and Path(v["path"]).exists()],
        key=lambda x: x.get("start_ms", 0),
    )

    if not compose_visuals:
        print("ERROR: No rendered visual clips found to compose", file=sys.stderr)
        return 1

    compose_with_ffmpeg(audio_path, compose_visuals, out_path, total_ms)

    # Write updated summary.
    summary = {
        "final_mp4": str(out_path),
        "final_duration_ms": total_ms,
        "final_duration_readable": f"{total_ms // 60000}m {(total_ms % 60000) // 1000}s",
        "audio_path": str(audio_path),
        "audio_duration_ms": total_ms,
        "visual_count": len(compose_visuals),
        "visuals": [
            {
                "visual_id": v["visual_id"],
                "template": v["template"],
                "path": v["path"],
                "start_ms": v["start_ms"],
                "end_ms": v["end_ms"],
                "duration_ms": v["duration_ms"],
            }
            for v in compose_visuals
        ],
    }
    (build_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    print(f"\nDone! Output: {out_path}", file=sys.stderr)
    print(f"  {len(compose_visuals)} visuals, {total_ms/1000:.1f}s total", file=sys.stderr)
    if not args.no_upload:
        _try_youtube_upload(out_path, episode=episode, run_dir=build_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
